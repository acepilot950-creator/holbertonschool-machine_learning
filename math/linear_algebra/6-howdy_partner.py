#!/usr/bin/env python3
"""Module that provides array concatenation."""


def cat_arrays(arr1, arr2):
    """Concatenate two arrays.

    Args:
        arr1 (list): First list of numbers.
        arr2 (list): Second list of numbers.

    Returns:
        list: New list containing elements of arr1 followed by arr2.
    """
    return arr1 + arr2
